// Compares what the setup engine promised with what happened, and writes the track record the terminal shows.
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { run, stats, type Rule, type Trade } from "../lib/backtest.ts";
import { load, row } from "./bt-load.ts";

const DAY = 86400;
const { data, cands, asOf } = load();
const LIMIT: Rule = { entry: "limit", valid: 48, hold: 168, stopAtr: null, target: "level" };
const CONFIRM: Rule = { ...LIMIT, entry: "confirm" };
const top = (c: { rank: number }) => c.rank === 0;

console.log("=== PROMISED vs ACTUAL, entries at the model's own price");
const tr = run(cands, data, LIMIT, top).filter((t) => t.how !== "time");
console.log("promised win    trades   actual win   promised EV   actual EV");
for (let lo = 0.1; lo < 0.8; lo += 0.1) {
  const g = tr.filter((t) => t.cand.pWin >= lo && t.cand.pWin < lo + 0.1);
  if (g.length < 15) continue;
  const ev = g.reduce((s, t) => s + t.cand.expR, 0) / g.length;
  const s = stats(g);
  console.log(`${(lo * 100).toFixed(0).padStart(3)}-${((lo + 0.1) * 100).toFixed(0)}%       ${String(g.length).padStart(5)}      ${(g.filter((t) => t.how === "target").length / g.length * 100).toFixed(0).padStart(3)}%         ${ev.toFixed(2).padStart(5)}R       ${s.avg.toFixed(2).padStart(5)}R`);
}
const allT = run(cands, data, CONFIRM, top);
console.log("\n=== Waiting for the trigger, by score band");
for (const [a, b] of [[0, 50], [50, 55], [55, 60], [60, 65], [65, 70], [70, 100]]) console.log(row(`score ${a}-${b}`, allT.filter((t) => t.cand.score >= a && t.cand.score < b)));

const record = (x: Trade[]) => {
  const s = stats(x);
  return { n: s.n, win: +s.win.toFixed(3), avg: +s.avg.toFixed(3), total: +s.total.toFixed(1), t: +s.t.toFixed(2) };
};
// Straight line from promised win rate to actual win rate.
const mp = tr.reduce((s, t) => s + t.cand.pWin, 0) / tr.length;
const my = tr.filter((t) => t.how === "target").length / tr.length;
let [sxy, sxx] = [0, 0];
for (const t of tr) {
  sxy += (t.cand.pWin - mp) * ((t.how === "target" ? 1 : 0) - my);
  sxx += (t.cand.pWin - mp) ** 2;
}
const b = sxy / sxx;
const a = my - b * mp;
console.log(`\nactual win = ${a.toFixed(3)} + ${b.toFixed(3)} x promised win`);
const by = (key: (t: Trade) => string) => {
  const m: Record<string, Trade[]> = {};
  for (const t of allT) (m[key(t)] ??= []).push(t);
  return Object.fromEntries(Object.entries(m).map(([k, v]) => [k, record(v)]));
};
const from = cands[0].T;
writeFileSync(
  resolve(import.meta.dirname, "../lib/record.ts"),
  `// Generated by scripts/calibrate.ts. Do not edit by hand.\nexport const RECORD = ${JSON.stringify({ asOf, from, calib: { a: +a.toFixed(4), b: +b.toFixed(4) }, overall: record(allT), last30: record(allT.filter((t) => t.T >= asOf - 30 * DAY)), bySetup: by((t) => t.name), byCoin: by((t) => t.sym) }, null, 1)} as {\n  asOf: number;\n  from: number;\n  calib: { a: number; b: number };\n  overall: Tested;\n  last30: Tested;\n  bySetup: Record<string, Tested>;\n  byCoin: Record<string, Tested>;\n};\ntype Tested = { n: number; win: number; avg: number; total: number; t: number };\n`,
);
console.log("wrote lib/record.ts");
