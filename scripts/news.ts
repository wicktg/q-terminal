// Check the news pipeline: rules on fixed headlines, then the live ranking.
import { getNews, rank } from "../lib/news.ts";
const now = Date.now();
const raw = (title: string) => ({ title, link: "https://x.y", t: now - 6e5, source: "t" });
const one = (t: string) => rank([raw(t)], now)[0];
const assert = (ok: boolean, m: string) => { if (!ok) throw new Error("FAILED: " + m); };
assert(one("Iran ceasefire talks collapse after strikes")?.bias === "RISK-OFF", "failed talks are risk-off");
assert(one("US and Iran sign peace deal")?.bias === "RISK-ON", "peace is risk-on");
assert(one("Hackers steal $6 billion from exchange")?.category === "HACK", "hack category");
assert(one("Bitcoin ETF outflows hit $600 million")?.bias === "RISK-OFF", "outflows");
assert(!one("Top 5 coins to buy now, could hit $10"), "spam dropped");
assert(!one("Local bakery wins award"), "irrelevant dropped");
assert(rank([raw("Binance hack drains $6 billion"), { ...raw("Binance hack drains $6 billion, report says"), source: "u" }], now).length === 1, "duplicates merge");
assert(one("Iran accuses Israel of breach of the ceasefire")?.category === "WAR", "breach of ceasefire is not a hack");
assert(one("BTC, ETH, XRP Plunge After Binance Incident")?.category === "HACK", "venue incident counts as hack");
assert(one("US greenlights $2.1bn Patriot missile sale")?.bias === "UNCLEAR", "arms sale is not escalation");
assert(one("Iran-US draft proposes uranium transfer, Hormuz reopening within 7 days")?.bias === "RISK-ON", "reopening is risk-on");
assert(one("Iran-US draft proposes uranium transfer, Hormuz reopening within 7 days")?.impact === "HIGH", "Hormuz story is high impact");
assert(!one("XRP price at Oct 31, 2026 at 2am EDT Crypto Prediction Market"), "prediction pages dropped");
assert(!one("Why AAVE crypto traders must watch $113 support"), "must-watch pieces dropped");
assert(one("Oil transports through Red Sea disrupted by war")?.category === "WAR", "transports is not sports");
assert(rank([raw("Binance's $6.3B hack tests customer trust"), { ...raw("Bitcoin drops as Binance hack hits $6.3B"), source: "u" }], now).length === 1, "same venue hack merges");
console.log("rules passed");
const n = await getNews();
console.log(`feeds ${n.feedsOk}/${n.feedsTotal}, items ${n.items.length}, HIGH ${n.items.filter((i) => i.impact === "HIGH").length}, MED ${n.items.filter((i) => i.impact === "MED").length}, LOW ${n.items.filter((i) => i.impact === "LOW").length}`);
const m = (t: number) => Math.round((now - t) / 6e4);
console.log("--- HOTTEST");
[...n.items].sort((a, b) => b.hot - a.hot).slice(0, 16).forEach((i) => console.log(`${String(m(i.t)).padStart(4)}m ${i.impact.padEnd(4)} ${i.category.padEnd(6)} ${i.bias.padEnd(8)} src${i.sources} ${i.score} ${i.title.slice(0, 90)}`));
console.log("--- NEWEST");
n.items.slice(0, 12).forEach((i) => console.log(`${String(m(i.t)).padStart(4)}m ${i.impact.padEnd(4)} ${i.category.padEnd(6)} ${i.bias.padEnd(8)} ${i.title.slice(0, 90)}`));
