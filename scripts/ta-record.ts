// Picks each live lane's settings from older data alone, then records how they did on everything after.
// Rewrites lib/lanes.ts and lib/ta-record.ts.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { FAMILY, runCoin, type Cfg, type Tf, type Trade } from "../lib/mtf.ts";
import { asOfOf, DAY, envs, loadCoin, OUT, summary, universe, type Coin } from "./mtf-lib.ts";

type Row = { cfg: Cfg; n: number; avg: number; t: number };
const pick = (tf: Tf) => {
  const rows = (JSON.parse(readFileSync(resolve(OUT, `search-${tf}-smc.json`), "utf8")) as { rows: Row[] }).rows;
  return rows.filter((r) => r.cfg.side === 0 && r.cfg.htf === "none" && r.n >= 60).sort((a, b) => b.t - a.t)[0];
};
const watch = universe.watch.map(loadCoin).filter((c): c is Coin => !!c);
const hold = universe.hold.map(loadCoin).filter((c): c is Coin => !!c);
const btc = watch.find((c) => c.sym === "BTC")!;
const asOf = asOfOf(btc);
const start = btc.base.t[0];
const finalFrom = asOf - 30 * DAY;
const validFrom = asOf - 210 * DAY;
const run = (coins: Coin[], cfg: Cfg) => {
  const es = envs(coins, btc, cfg.tf);
  const out: Trade[] = [];
  es.forEach((e, i) => out.push(...runCoin(e, FAMILY[cfg.fam].sig(e, cfg.p), cfg, coins[i].fund, i)));
  return out;
};
const lanes: Record<string, { tf: Tf; p: Cfg["p"]; r: number }> = {};
const rows: { lane: string; n: number; older: number; unseen: number; hold: number; last30: number; t: number }[] = [];
for (const [lane, tf] of [["HTF", "4h"], ["LTF", "15m"]] as [string, Tf][]) {
  const best = pick(tf);
  const cfg = best.cfg;
  lanes[lane] = { tf, p: cfg.p, r: cfg.ex.target };
  const w = run(watch, cfg);
  const h = run(hold, cfg);
  const [o, u, l, hs] = [summary(w, start, validFrom), summary(w, validFrom, finalFrom), summary(w, finalFrom, asOf + DAY), summary(h, start, finalFrom)];
  rows.push({ lane: `${lane} ${tf.toUpperCase()}`, n: w.length + h.length, older: +o.avg.toFixed(3), unseen: +u.avg.toFixed(3), hold: +hs.avg.toFixed(3), last30: +l.avg.toFixed(3), t: +o.t.toFixed(2) });
  console.log(lane, tf, JSON.stringify(cfg.p), `exit ${JSON.stringify(cfg.ex)}`);
  console.log(`  older ${o.n}/${o.avg.toFixed(3)}R t ${o.t.toFixed(2)} | unseen ${u.n}/${u.avg.toFixed(3)}R t ${u.t.toFixed(2)} | UNI+AERO ${hs.n}/${hs.avg.toFixed(3)}R t ${hs.t.toFixed(2)} | last30 ${l.n}/${l.avg.toFixed(3)}R`);
}
writeFileSync(
  resolve(import.meta.dirname, "../lib/lanes.ts"),
  `// Generated by scripts/ta-record.ts from older data only. HTF plans the trade, LTF times it.
import type { Tf } from "./mtf.ts";
import type { SmcParams } from "./ta.ts";

// r is a fixed target in multiples of risk. Zero means the next liquidity.
export const LANES: Record<"HTF" | "LTF", { tf: Tf; p: SmcParams; r: number }> = ${JSON.stringify(lanes, null, 2)} as never;
`,
);
const passed = rows.every((r) => r.t >= 2 && r.unseen > 0);
const d = (t: number) => new Date(t * 1000).toISOString().slice(0, 10);
writeFileSync(
  resolve(import.meta.dirname, "../lib/ta-record.ts"),
  `// Generated by scripts/ta-record.ts. Do not edit by hand.
export const TESTED = ${JSON.stringify({ period: `${d(start)} to ${d(asOf)}`, verdict: passed ? "Both lanes cleared the first bar on older data." : "No proven edge: neither lane cleared the first test bar on older data, so read these as structure, not as a reason to size up.", rows: rows.map(({ t: _t, ...r }) => r) }, null, 2)};
`,
);
console.log("wrote lanes and record");
