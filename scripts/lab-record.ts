// Picks each lab setup's settings from older data only, measures them on everything later, and rewrites lib/lab-record.ts.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { FAMILY, runCoin, type Cfg, type Tf, type Trade } from "../lib/mtf.ts";
import { asOfOf, DAY, envs, loadCoin, OUT, summary, universe, type Coin } from "./mtf-lib.ts";

type Row = { id: string; cfg: Cfg; n: number; avg: number; t: number; pos: number };
const NAMES: Record<string, string> = { G1: "unseen months", G2: "unseen coins", G3: "time blocks", G4: "overfit probability", G5: "deflated Sharpe", G6: "cost and delay", G7: "parameter jitter", G8: "both BTC regimes", G9: "alpha", G10: "bootstrap", G11: "random timing", G12: "synthetic paths" };
const LANES: Record<string, Tf[]> = { LTF: ["5m", "15m", "1h"], HTF: ["4h", "1d"] };
const FAMS = ["labcont", "labrev", "labdev", "labmtf"];
const MIN: Record<Tf, number> = { "5m": 150, "15m": 150, "1h": 100, "4h": 60, "1d": 30 };
const search: Record<string, Row[]> = {};
const gates: Record<string, { id: string; gates: Record<string, boolean>; passedCount: number; passed: boolean }[]> = {};
let shortlisted = 0;
for (const tf of ["5m", "15m", "1h", "4h", "1d"]) {
  search[tf] = (JSON.parse(readFileSync(resolve(OUT, `search-${tf}-lab.json`), "utf8")) as { rows: Row[] }).rows;
  const f = resolve(OUT, `gates-${tf}-lab.json`);
  if (existsSync(f)) {
    const g = JSON.parse(readFileSync(f, "utf8")) as { results: (typeof gates)[string]; shortlist: number };
    gates[tf] = g.results;
    shortlisted += g.shortlist;
  }
}
const all = Object.values(gates).flat();
const trials = Object.values(search).reduce((s, r) => s + r.length, 0);
const watch = universe.watch.map(loadCoin).filter((c): c is Coin => !!c);
const hold = universe.hold.map(loadCoin).filter((c): c is Coin => !!c);
const btc = watch.find((c) => c.sym === "BTC")!;
const asOf = asOfOf(btc);
const start = btc.base.t[0];
const finalFrom = asOf - 30 * DAY;
const validFrom = asOf - 210 * DAY;
const cache = new Map<string, ReturnType<typeof envs>>();
const envFor = (coins: Coin[], tf: Tf, tag: string) => {
  const k = `${tag}${tf}`;
  if (!cache.has(k)) cache.set(k, envs(coins, btc, tf));
  return cache.get(k)!;
};
const run = (coins: Coin[], cfg: Cfg, tag: string) => {
  const out: Trade[] = [];
  envFor(coins, cfg.tf, tag).forEach((e, i) => out.push(...runCoin(e, FAMILY[cfg.fam].sig(e, cfg.p), cfg, coins[i].fund, i)));
  return out;
};
const rows: unknown[] = [];
for (const [lane, tfs] of Object.entries(LANES))
  for (const fam of FAMS) {
    // Both directions only, so a setup cannot look good simply by shorting a falling market.
    const pool = tfs.flatMap((tf) => search[tf].filter((r) => r.cfg.fam === fam && r.cfg.side === 0 && r.n >= MIN[r.cfg.tf]));
    const best = pool.sort((a, b) => b.t - a.t)[0];
    if (!best) continue;
    const cfg = best.cfg;
    const [w, h] = [run(watch, cfg, "w"), run(hold, cfg, "h")];
    const [o, u, l, hs] = [summary(w, start, validFrom), summary(w, validFrom, finalFrom), summary(w, finalFrom, asOf + DAY), summary(h, start, finalFrom)];
    const g = gates[cfg.tf]?.find((x) => x.id === best.id);
    rows.push({ key: `${lane}-${fam}`, lane, fam, tf: cfg.tf, p: cfg.p, r: cfg.ex.target, trail: cfg.ex.trail, side: cfg.side, n: o.n, older: +o.avg.toFixed(3), olderT: +o.t.toFixed(2), unseen: +u.avg.toFixed(3), unseenN: u.n, hold: +hs.avg.toFixed(3), holdN: hs.n, last30: +l.avg.toFixed(3), last30N: l.n, gates: g?.passedCount ?? 0, failed: g ? Object.entries(g.gates).filter(([, ok]) => !ok).map(([k]) => NAMES[k]) : ["first bar on older data"] });
    console.log(`${lane} ${fam} ${cfg.tf} ${JSON.stringify(cfg.p)} exit ${JSON.stringify(cfg.ex)}`);
    console.log(`   older ${o.n}/${o.avg.toFixed(3)}R t ${o.t.toFixed(2)} | unseen ${u.n}/${u.avg.toFixed(3)}R t ${u.t.toFixed(2)} | UNI+AERO ${hs.n}/${hs.avg.toFixed(3)}R t ${hs.t.toFixed(2)} | last30 ${l.n}/${l.avg.toFixed(3)}R | gates ${g?.passedCount ?? "-"}`);
  }
const best = Math.max(0, ...all.map((x) => x.passedCount));
const survivors = all.filter((x) => x.passed).length;
const d = (t: number) => new Date(t * 1000).toISOString().slice(0, 10);
const verdict = survivors ? `${survivors} setups passed all 12 gates.` : `None of the ${shortlisted} shortlisted variations passed all 12 gates. The best reached ${best} of 12.`;
writeFileSync(
  resolve(import.meta.dirname, "../lib/lab-record.ts"),
  `// Generated by scripts/lab-record.ts. Do not edit by hand.
export const LAB_SETUPS: { key: string; lane: string; fam: string; tf: string; p: Record<string, number>; r: number; trail: number; side: number; n: number; older: number; olderT: number; unseen: number; unseenN: number; hold: number; holdN: number; last30: number; last30N: number; gates: number; failed: string[] }[] = ${JSON.stringify(rows, null, 1)};
export const LAB_META = ${JSON.stringify({ verdict, trials, shortlisted, best, period: `${d(start)} to ${d(asOf)}` })};
`,
);
console.log(`trials ${trials}, shortlisted ${shortlisted}, best ${best}/12, survivors ${survivors}`);
const gatePass = Object.keys(NAMES).map((k) => `${NAMES[k]} ${all.filter((x) => x.gates[k]).length}`);
console.log(`gate passes of ${all.length}: ${gatePass.join(", ")}`);
for (const x of [...all].sort((a, b) => b.passedCount - a.passedCount).slice(0, 10)) console.log(`${x.passedCount}/12 ${x.id} fails ${Object.entries(x.gates).filter(([, ok]) => !ok).map(([k]) => k).join(" ")}`);
